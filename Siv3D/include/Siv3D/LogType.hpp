# pragma once
# include "Types.hpp"

namespace s3d
{
	struct FormatData;

	////////////////////////////////////////////////////////////////
	//
	//	LogType
	//
	////////////////////////////////////////////////////////////////

	/// @brief ログの種類 | The type of the log message
	enum class LogType : uint8
	{
		////////////////////////////////////////////////////////////////
		//
		//	LogType::Error
		//
		////////////////////////////////////////////////////////////////

		/// @brief エラー | Error
		Error,

		////////////////////////////////////////////////////////////////
		//
		//	LogType::Fail
		//
		////////////////////////////////////////////////////////////////

		/// @brief 失敗 | Fail
		Fail,

		////////////////////////////////////////////////////////////////
		//
		//	LogType::Warning
		//
		////////////////////////////////////////////////////////////////

		/// @brief 警告 | Warning
		Warning,

		////////////////////////////////////////////////////////////////
		//
		//	LogType::App
		//
		////////////////////////////////////////////////////////////////

		/// @brief アプリケーション | Application
		App,

		////////////////////////////////////////////////////////////////
		//
		//	LogType::Info
		//
		////////////////////////////////////////////////////////////////

		/// @brief 情報 | Information
		Info,

		////////////////////////////////////////////////////////////////
		//
		//	LogType::Debug
		//
		////////////////////////////////////////////////////////////////

		/// @brief デバッグ | Debug
		Debug,

		////////////////////////////////////////////////////////////////
		//
		//	LogType::Trace
		//
		////////////////////////////////////////////////////////////////

		/// @brief トレース | Trace
		Trace,
	};

	////////////////////////////////////////////////////////////////
	//
	//	Formatter
	//
	////////////////////////////////////////////////////////////////

	/// @brief ログの種類を文字列に変換します。
	/// @param formatData 文字列バッファ
	/// @param value ログの種類
	/// @remark この関数は Format 用の関数です。通常、ユーザーが直接呼び出す必要はありません。
	void Formatter(FormatData& formatData, LogType value);
}
