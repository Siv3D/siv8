# pragma once
# include "Types.hpp"

namespace s3d
{
	struct FormatData;

	////////////////////////////////////////////////////////////////
	//
	//	LogLevel
	//
	////////////////////////////////////////////////////////////////

	/// @brief ログレベル | Log level
	enum class LogLevel : uint8
	{
		////////////////////////////////////////////////////////////////
		//
		//	LogLevel::Error
		//
		////////////////////////////////////////////////////////////////

		/// @brief エラー | Error
		Error,

		////////////////////////////////////////////////////////////////
		//
		//	LogLevel::Fail
		//
		////////////////////////////////////////////////////////////////

		/// @brief 失敗 | Fail
		Fail,

		////////////////////////////////////////////////////////////////
		//
		//	LogLevel::Warning
		//
		////////////////////////////////////////////////////////////////

		/// @brief 警告 | Warning
		Warning,

		////////////////////////////////////////////////////////////////
		//
		//	LogLevel::App
		//
		////////////////////////////////////////////////////////////////

		/// @brief アプリケーション | Application
		App,

		////////////////////////////////////////////////////////////////
		//
		//	LogLevel::Info
		//
		////////////////////////////////////////////////////////////////

		/// @brief 情報 | Information
		Info,

		////////////////////////////////////////////////////////////////
		//
		//	LogLevel::Debug
		//
		////////////////////////////////////////////////////////////////

		/// @brief デバッグ | Debug
		Debug,

		////////////////////////////////////////////////////////////////
		//
		//	LogLevel::Trace
		//
		////////////////////////////////////////////////////////////////

		/// @brief トレース | Trace
		Trace,
	};

	////////////////////////////////////////////////////////////////
	//
	//	Formatter
	//
	////////////////////////////////////////////////////////////////

	/// @brief ログレベルを文字列に変換します。
	/// @param formatData 文字列バッファ
	/// @param value ログレベル
	/// @remark この関数は Format 用の関数です。通常、ユーザーが直接呼び出す必要はありません。
	void Formatter(FormatData& formatData, LogLevel value);
}
