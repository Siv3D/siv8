# pragma once
# include <memory>
# include "Common.hpp"
# include "Byte.hpp"
# include "String.hpp"
# include "MappedMemory.hpp"

namespace s3d
{
	////////////////////////////////////////////////////////////////
	//
	//	MemoryMappedFile
	//
	////////////////////////////////////////////////////////////////

	/// @brief メモリマップトファイル
	/// @remark 同時にマップできるのは 1 範囲です。返される範囲は所有権を持たず、アンマップ・クローズ・破棄で無効になります。
	/// @remark オープン中に、外部からファイルのサイズを変更しないでください。
	class MemoryMappedFile
	{
	public:

		////////////////////////////////////////////////////////////////
		//
		//	ExistingFilePolicy
		//
		////////////////////////////////////////////////////////////////

		/// @brief 存在するファイルをオープンする際の方針
		enum class ExistingFilePolicy : uint8
		{
			/// @brief ファイルが存在する場合、失敗にします。
			Fail,

			/// @brief ファイルが存在する場合、そのファイルをオープンします。
			JustOpen,

			/// @brief ファイルが存在する場合、ファイルをオープンしてサイズを 0 にします。
			Truncate,
		};

		////////////////////////////////////////////////////////////////
		//
		//	MissingFilePolicy
		//
		////////////////////////////////////////////////////////////////

		/// @brief 存在しないファイルをオープンする際の方針
		enum class MissingFilePolicy : uint8
		{
			/// @brief ファイルが存在しない場合、失敗にします。
			Fail,

			/// @brief ファイルが存在しない場合、新規作成します。
			Create,
		};

		////////////////////////////////////////////////////////////////
		//
		//	(constructor)
		//
		////////////////////////////////////////////////////////////////

		/// @brief デフォルトコンストラクタ
		[[nodiscard]]
		MemoryMappedFile();

		/// @brief メモリマップトファイルをオープンします。
		/// @param path ファイルパス
		/// @param ifExists ファイルが存在する場合の方針
		/// @param ifNotFound ファイルが存在しない場合の方針
		[[nodiscard]]
		MemoryMappedFile(FilePathView path, ExistingFilePolicy ifExists, MissingFilePolicy ifNotFound = MissingFilePolicy::Create);

		MemoryMappedFile(const MemoryMappedFile& other) = delete;

		/// @brief ファイルとマップの所有権を移します。取得済みの範囲はムーブ先がアンマップするまで存続します。
		/// @param other ムーブする MemoryMappedFile。ムーブ元は閉じた状態となり、再オープンできます。
		MemoryMappedFile(MemoryMappedFile&& other) noexcept;

		////////////////////////////////////////////////////////////////
		//
		//	(destructor)
		//
		////////////////////////////////////////////////////////////////

		/// @brief デストラクタ
		~MemoryMappedFile();

		////////////////////////////////////////////////////////////////
		//
		//	operator =
		//
		////////////////////////////////////////////////////////////////

		MemoryMappedFile& operator =(const MemoryMappedFile& other) = delete;

		/// @brief 現在のファイルを閉じ、ファイルとマップの所有権を移します。
		/// @remark 自己ムーブ代入では状態を変更しません。
		/// @param other ムーブする MemoryMappedFile。自己代入以外では、ムーブ元は閉じた状態となり、再オープンできます。
		/// @return *this
		MemoryMappedFile& operator =(MemoryMappedFile&& other) noexcept;

		////////////////////////////////////////////////////////////////
		//
		//	open
		//
		////////////////////////////////////////////////////////////////

		/// @brief メモリマップトファイルをオープンします。
		/// @param path 通常ファイルのパス。空のパスや NUL を含むパスは受け付けません。
		/// @param ifExists ファイルが存在する場合の方針
		/// @param ifNotFound ファイルが存在しない場合の方針
		/// @return メモリマップトファイルがオープンに成功した場合 true, それ以外の場合は false
		/// @remark 現在のファイルとマップを置き換えます。false を返した場合は閉じた状態になります。
		/// @remark 作成・切り詰め済みのファイルは、後続処理が失敗しても元に戻しません。Resource() のパスには書き込めません。
		bool open(FilePathView path, ExistingFilePolicy ifExists, MissingFilePolicy ifNotFound = MissingFilePolicy::Create);

		////////////////////////////////////////////////////////////////
		//
		//	close
		//
		////////////////////////////////////////////////////////////////

		/// @brief メモリマップトファイルをクローズします。
		/// @remark マップ中であれば自動的にアンマップします。書き込みは取り消されません。完了を検査する場合は先に flush() を呼びます。
		void close();

		////////////////////////////////////////////////////////////////
		//
		//	isOpen
		//
		////////////////////////////////////////////////////////////////

		/// @brief メモリマップトファイルがオープンしているかを返します。
		/// @return メモリマップトファイルがオープンしている場合 true, それ以外の場合は false
		[[nodiscard]]
		bool isOpen() const;

		////////////////////////////////////////////////////////////////
		//
		//	operator bool
		//
		////////////////////////////////////////////////////////////////

		/// @brief メモリマップトファイルがオープンしているかを返します。
		/// @return メモリマップトファイルがオープンしている場合 true, それ以外の場合は false
		/// @remark `isOpen()` と同じです。
		[[nodiscard]]
		explicit operator bool() const;

		////////////////////////////////////////////////////////////////
		//
		//	map
		//
		////////////////////////////////////////////////////////////////

		/// @brief メモリマップトファイルの指定した範囲をマップします。
		/// @param offset マップする範囲の先頭位置（バイト）。0 から size() まで指定できます。
		/// @param requestSize マップするバイト数。ファイルの終端を越える場合はファイルを拡張します。
		/// @return マップされた範囲。未オープン、マップ済み、requestSize が 0、offset > size()、範囲の終端が INT64_MAX を越える場合、または OS の処理が失敗した場合は { nullptr, 0 }。
		/// @remark 失敗した再マップは既存のマップを保持します。拡張後にマップが失敗した場合も、ファイルの拡張は取り消しません。
		/// @remark 拡張部分の初期値は保証しません。必要な内容を書き込んでから読み出してください。
		[[nodiscard]]
		MappedMemory map(size_t offset, size_t requestSize);

		////////////////////////////////////////////////////////////////
		//
		//	mapAll
		//
		////////////////////////////////////////////////////////////////

		/// @brief メモリマップトファイル全体をマップします。
		/// @return map(0, size()) の結果。空のファイルは { nullptr, 0 }。
		[[nodiscard]]
		MappedMemory mapAll();

		////////////////////////////////////////////////////////////////
		//
		//	unmap
		//
		////////////////////////////////////////////////////////////////

		/// @brief 現在の範囲をアンマップします。ファイルは開いたままで、再びマップできます。
		/// @remark マップしていない場合は何もしません。
		void unmap();

		////////////////////////////////////////////////////////////////
		//
		//	flush
		//
		////////////////////////////////////////////////////////////////

		/// @brief マップへの書き込みとファイルのバッファを同期的にフラッシュします。
		/// @return 同期処理に成功した場合 true, ファイルが閉じているか同期処理が失敗した場合は false
		/// @remark アンマップ後も、ファイルを閉じるまでは同期できます。
		bool flush();

		////////////////////////////////////////////////////////////////
		//
		//	size
		//
		////////////////////////////////////////////////////////////////

		/// @brief メモリマップトファイルのサイズを返します。
		/// @return オープン時のファイルサイズに、このオブジェクトによる拡張を反映したバイト数。閉じた状態では 0。
		[[nodiscard]]
		int64 size() const;

		////////////////////////////////////////////////////////////////
		//
		//	path
		//
		////////////////////////////////////////////////////////////////

		/// @brief メモリマップトファイルのパスを返します。
		/// @return 開いているファイルのフルパス。閉じた状態では空の文字列への参照。
		[[nodiscard]]
		const FilePath& path() const;

	private:

		class MemoryMappedFileDetail;

		std::unique_ptr<MemoryMappedFileDetail> pImpl;
	};
}
